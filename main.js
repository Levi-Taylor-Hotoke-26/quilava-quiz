let currentQuestionIndex = 0;
let correctAnswers = 0;

function normalizeAnswer(value) {
  return value.trim().toLowerCase().replace(/[^a-z0-9]/g, '');
}

function renderQuestion(question) {
  if (questionOneImage) {
    questionOneImage.src = question.image;
  }

  if (questionOneText) {
    questionOneText.textContent = question.prompt;
  }

  if (answerInput) {
    answerInput.value = '';
    answerInput.disabled = false;
  }
}

function updateExperienceDisplay() {
  const experiencePoints = correctAnswers * experiencePerCorrectAnswer;

  if (experienceCounter) {
    experienceCounter.textContent = `Experience Points: ${experiencePoints}`;
  }

  if (evolutionImage) {
    if (correctAnswers >= typhlosionEvolutionAtCorrectAnswers) {
      evolutionImage.src = evolvedImage;
      evolutionImage.alt = 'Typhlosion';
    } else if (correctAnswers >= quilavaEvolutionAtCorrectAnswers) {
      evolutionImage.src = quilavaImage;
      evolutionImage.alt = 'Quilava';
    } else {
      evolutionImage.src = baseEvolutionImage;
      evolutionImage.alt = 'Cyndaquil';
    }
  }
}

function updateBadgeDisplay() {
  const badgesEarned = Math.min(Math.floor(correctAnswers / 5), badgeNames.length);

  if (badgeCounter) {
    badgeCounter.textContent = `Gym Badges: ${badgesEarned} / ${badgeNames.length}`;
  }

  if (badgeCollection) {
    badgeCollection.innerHTML = badgeNames.map((badgeName, index) => {
      const earned = correctAnswers >= (index + 1) * 5;
      const badgeImage = badgeImages[badgeName];

      return `
        <span class="gym-badge ${earned ? 'earned' : ''}">
          ${earned ? `<img src="${badgeImage}" alt="${badgeName}" />` : ''}
          <span>${badgeName}</span>
        </span>
      `;
    }).join('');
  }
}

function celebrateEvolution(message) {
  alert(message);
  cheeringAudio.currentTime = 0;
  cheeringAudio.play().catch(function () {
    return null;
  });
}

renderQuestion(quizQuestions[currentQuestionIndex]);
updateExperienceDisplay();
updateBadgeDisplay();

if (answerForm) {
  answerForm.addEventListener('submit', function (event) {
    event.preventDefault();

    const currentQuestion = quizQuestions[currentQuestionIndex];
    const userAnswer = answerInput ? normalizeAnswer(answerInput.value) : '';
    const expectedAnswer = normalizeAnswer(currentQuestion.answer);

    if (userAnswer === expectedAnswer) {
      const previousCorrectAnswers = correctAnswers;
      correctAnswers += 1;
      updateExperienceDisplay();
      updateBadgeDisplay();

      if (previousCorrectAnswers < quilavaEvolutionAtCorrectAnswers && correctAnswers >= quilavaEvolutionAtCorrectAnswers) {
        celebrateEvolution('Cyndaquil evolved into Quilava!');
      }

      if (previousCorrectAnswers < typhlosionEvolutionAtCorrectAnswers && correctAnswers >= typhlosionEvolutionAtCorrectAnswers) {
        celebrateEvolution('Quilava evolved into Typhlosion!');
      }

      if (feedback) {
        feedback.textContent = 'Correct!';
      }

      currentQuestionIndex += 1;

      if (currentQuestionIndex < quizQuestions.length) {
        renderQuestion(quizQuestions[currentQuestionIndex]);
      } else if (answerInput) {
        answerInput.disabled = true;
        if (feedback) {
          feedback.textContent = "Quiz complete! Your Quilava evolved into a Typhlosion and now you're ready to take on the elite four!";
        }
      }
    } else if (feedback) {
      feedback.textContent = 'Try again.';
    }

    if (answerInput && currentQuestionIndex < quizQuestions.length) {
      answerInput.value = '';
    }
  });
}
